/**
 * Writes docs/TEST-CASES.md from a real run of the test suite, so the list always matches the code.
 *
 *   npm run test-cases
 */
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const mocha = path.join(root, 'node_modules', 'mocha', 'bin', 'mocha.js');
let raw;
try {
  raw = execFileSync(process.execPath, [mocha, '--timeout=60000', '--exit', '--reporter', 'json'], { cwd: root, encoding: 'utf8' });
} catch (error) {
  raw = error.stdout; // failing tests still produce a report; they show as ❌
}
const report = JSON.parse(raw.slice(raw.indexOf('{')));
const failed = new Set(report.failures.map((t) => t.fullTitle));

const bySuite = new Map();
for (const t of report.tests) {
  const file = path.basename(t.file || '');
  const suite = t.fullTitle.slice(0, t.fullTitle.length - t.title.length).trim();
  const key = `${file}|${suite}`;
  if (!bySuite.has(key)) bySuite.set(key, { file, suite, tests: [] });
  bySuite.get(key).tests.push({ title: t.title, ok: !failed.has(t.fullTitle) });
}

const { tests, passes, failures } = report.stats;
let md = `# Test cases

Generated by \`npm run test-cases\` from a run of the automated suite on ${new Date().toISOString().slice(0, 10)}.

**${passes} of ${tests} passing${failures ? `, ${failures} failing` : ''}.** The tests run against a real in-memory MongoDB
(\`mongodb-memory-server\`) through the real Express app (\`supertest\`), with sessions and CSRF on. Calls to Claude are
replaced with stubs, so no API key is needed and results are the same on every run.

Run them with \`npm test\`. The scripted sandbox scenario in [evidence/README.md](evidence/README.md) (\`npm run evidence\`)
complements these with an end-to-end operation log.
`;
for (const { file, suite, tests: list } of bySuite.values()) {
  md += `\n## ${suite} (\`test/${file}\`)\n\n`;
  md += list.map((t) => `- ${t.ok ? '✅' : '❌'} ${t.title}`).join('\n');
  md += '\n';
}
fs.writeFileSync(path.join(root, 'docs', 'TEST-CASES.md'), md);
console.log(`docs/TEST-CASES.md: ${passes}/${tests} passing, ${bySuite.size} groups`);
